#!/usr/bin/env node
// Builds results/SUMMARY.md from the raw result files in results/ (CPU) and results/gpu-l4/ (GPU).
// Every number in the summary comes from those files; nothing is typed in by hand.
// usage: node benchmarks/merge-20261101/report.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { median, quantile } from './stats.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const R = path.join(here, 'results');
const G = path.join(R, 'gpu-l4');
const read = (file) => (fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null);
const f = (v, d = 3) => (v === null || v === undefined || !Number.isFinite(v) ? '–' : v.toFixed(d));
const pct = (ratio) => (Number.isFinite(ratio) ? `${ratio >= 1 ? '+' : '−'}${Math.abs((ratio - 1) * 100).toFixed(1)}%` : '–');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map((h, i) => (i === 0 ? '---' : '---:')).join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const lines = [];
const out = (...s) => lines.push(...s);

function geomeanCi(ratios, seed = 7) {
  let state = seed;
  const next = () => { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state / 0x100000000; };
  const g = (xs) => Math.exp(xs.reduce((a, v) => a + Math.log(v), 0) / xs.length);
  const boots = [];
  for (let i = 0; i < 20000; i++) boots.push(g(ratios.map(() => ratios[Math.floor(next() * ratios.length)])));
  boots.sort((a, b) => a - b);
  return { point: g(ratios), low: boots[500], high: boots[19500] };
}
// Speed ratio = baseline time / candidate time: above 1 the merged branch is faster.
const speed = (r) => `${f(r.point, 3)} [${f(r.low ?? r.low95, 3)}, ${f(r.high ?? r.high95, 3)}]`;

out('# Merge benchmark summary (generated)', '',
  'Generated by `node benchmarks/merge-20261101/report.mjs` from the raw files in this directory. Speed ratios are baseline time ÷ merged time: above 1.000 the merged branch is faster. Brackets are 95% bootstrap intervals. See `docs/BENCHMARKS_MERGE_20261101.md` for method, context and conclusions.', '');

// ---------------------------------------------------------------- CPU environment
const native = read(path.join(R, 'native-ab.json'));
if (native) {
  const e = native.environment;
  out('## CPU host', '', `${e.cpuModel}, ${e.logicalCpus} logical CPUs, ${e.totalMemoryGiB} GiB, Linux ${e.kernel}, Node ${e.node} (V8 ${e.v8}). Single-threaded runs pinned with \`taskset\` to CPU ${native.method.cpu}; nothing else measured at the same time.`, '');
}

// ---------------------------------------------------------------- native engine
if (native) {
  const ratios = native.cases.map((c) => c.speedRatioMeanStep.point);
  const ci = geomeanCi(ratios);
  out('## Native Box3D WASM (main binary vs merged binary)', '',
    `${native.cases.length} catalogue scenes (4 per rigid family), stress 5, ${native.method.warmup} warm-up + ${native.method.frames} timed \`b3w_step(1/60, 4)\` per sample, ${native.method.rounds} ABBA rounds of fresh processes.`, '',
    `- Geometric-mean speed ratio over scenes: **${speed(ci)}** (interval: bootstrap over scenes).`,
    `- Scenes with a significant difference: ${native.cases.filter((c) => c.verdict === 'candidate faster').length} faster, ${native.cases.filter((c) => c.verdict === 'candidate slower').length} slower, ${native.cases.filter((c) => c.verdict === 'no significant difference').length} no significant difference.`,
    `- Trajectories: ${native.cases.filter((c) => c.trajectory.startsWith('bit-identical')).length}/${native.cases.length} scenes bit-identical (replay hash every 30 frames); body counts equal in ${native.cases.filter((c) => c.sameBodyCount).length}/${native.cases.length}.`,
    `- Binary: ${native.baseline.wasmBytes.toLocaleString('en')} → ${native.candidate.wasmBytes.toLocaleString('en')} bytes (${pct(native.candidate.wasmBytes / native.baseline.wasmBytes)}); module load median ${f(median(native.cases.map((c) => c.baseline.loadMs.median)), 1)} → ${f(median(native.cases.map((c) => c.candidate.loadMs.median)), 1)} ms.`, '');
  out(table(['Family', 'Scenes', 'Bodies', 'Main ms/step', 'Merged ms/step', 'Speed ratio (geomean)'],
    Object.entries(native.summary.byFamily).map(([family, s]) => {
      const list = native.cases.filter((c) => c.family === family);
      return [family, s.scenes, list.map((c) => c.baseline.bodies).join('/'), f(median(list.map((c) => c.baseline.meanStepMs.median))), f(median(list.map((c) => c.candidate.meanStepMs.median))), f(s.geometricMeanSpeedRatio)];
    })), '');
}

// ---------------------------------------------------------------- soft bodies
for (const [file, label] of [['soft-ab-simd.json', 'SIMD WebAssembly kernels (the production path)'], ['soft-ab-javascript.json', 'JavaScript kernels (fallback path)']]) {
  const soft = read(path.join(R, file));
  if (!soft) continue;
  const ci = geomeanCi(soft.cases.map((c) => c.speedRatioMeanFrame.point));
  out(`## Soft-body suite, ${label}`, '',
    `${soft.cases.length} scenes (all 50 rope scenes plus every fifth cloth, water and fracture scene), stress ${soft.method.stress}, ${soft.method.warmup} warm-up + ${soft.method.frames} timed frames of \`step(1/60, 4)\` + \`buildFrame(false)\`, ${soft.method.rounds} ABBA rounds.`, '',
    `- Geometric-mean speed ratio: **${speed(ci)}**.`,
    `- Presented state (exact hash of instance matrices and colours every 30 frames): ${soft.cases.filter((c) => c.trajectory.startsWith('bit-identical')).length}/${soft.cases.length} scenes bit-identical.`, '');
  out(table(['Family', 'Scenes', 'Main ms/frame', 'Merged ms/frame', 'Speed ratio (geomean)', 'Faster', 'Slower', 'n.s.', 'Bit-identical'],
    Object.entries(soft.summary.families).map(([family, s]) => {
      const list = soft.cases.filter((c) => c.family === family);
      const fam = geomeanCi(list.map((c) => c.speedRatioMeanFrame.point));
      return [family, s.scenes, f(median(list.map((c) => c.baseline.meanFrameMs.median))), f(median(list.map((c) => c.candidate.meanFrameMs.median))), speed(fam), s.faster, s.slower, s.noSignificantDifference, s.bitIdenticalTrajectories];
    })), '');
  // Rope variants 2, 3 and 5 run batched kernel projection at stress 5 on main but the legacy per-constraint cadence
  // on the merged branch (ropeBatchProjectionEligible in src/soft/simulations.ts; rope scene variant = (id - 650) % 10).
  const rope = soft.cases.filter((c) => c.family === 'rope');
  if (rope.length && soft.method.stress === 5) {
    const policyChanged = rope.filter((c) => [2, 3, 5].includes((c.id - 650) % 10));
    const policySame = rope.filter((c) => ![2, 3, 5].includes((c.id - 650) % 10));
    const a = geomeanCi(policyChanged.map((c) => c.speedRatioMeanFrame.point));
    const b = geomeanCi(policySame.map((c) => c.speedRatioMeanFrame.point));
    out(`Rope scenes whose batching policy changed (variants 2, 3, 5; ${policyChanged.length} scenes): speed ratio ${speed(a)}. Rope scenes with the same policy (${policySame.length} scenes): ${speed(b)}.`, '');
  }
  const changed = soft.cases.filter((c) => !c.trajectory.startsWith('bit-identical'));
  if (changed.length) out(`Scenes whose presented state differs from main: ${changed.map((c) => `${c.id} (${c.title}; ${c.trajectory})`).join('; ')}.`, '');
  const extremes = [...soft.cases].sort((a, b) => a.speedRatioMeanFrame.point - b.speedRatioMeanFrame.point);
  out(`Largest slowdown: ${extremes[0].id} ${extremes[0].title} ${speed(extremes[0].speedRatioMeanFrame)}; largest speed-up: ${extremes.at(-1).id} ${extremes.at(-1).title} ${speed(extremes.at(-1).speedRatioMeanFrame)}.`, '');
}

// ---------------------------------------------------------------- long-horizon equivalence and rope batching
const longRun = read(path.join(R, 'soft-ab-simd-720-frames.json'));
if (longRun) {
  const diverged = longRun.cases.filter((c) => !c.trajectory.startsWith('bit-identical'));
  out('## Soft-body equivalence over 720 frames (SIMD kernels)', '',
    `Same ${longRun.cases.length} scenes, ${longRun.method.warmup + longRun.method.frames} frames (12 simulated seconds), ${longRun.method.rounds} ABBA rounds. Presented state bit-identical with main through frame 720 in ${longRun.cases.length - diverged.length}/${longRun.cases.length} scenes.${diverged.length ? ` Differs in: ${diverged.map((c) => `${c.id} ${c.title} (${c.trajectory})`).join('; ')}.` : ''}`, '');
}
const divergence = read(path.join(R, 'rope-batching-divergence.json'));
if (divergence) {
  const s = divergence.summary;
  out('## Rope batched projection vs the legacy cadence (rope-batching gate workload)', '',
    `Stress ${divergence.stress}, ${divergence.framesPerScene} frames, positions compared every ${divergence.checkEvery} frames. Under main's eligibility rule ${s.batchedOnMain} rope scenes run batched projection, and ${s.divergentWhenBatched} of them diverge from the legacy per-constraint cadence: ${s.divergentScenes.join('; ')}. The merged rule excludes every divergent scene: ${s.mergedRuleExcludesEveryDivergentScene}. Every scene still batched on the merged branch is identical to the legacy cadence: ${s.batchedOnMergedAndIdentical}. Scenes excluded on the merged branch that did not diverge: ${divergence.cases.filter((c) => c.batchedOnMain && !c.batchedOnMerged && c.firstDivergentFrame === null).map((c) => c.id).join(', ') || 'none'}.`, '');
}

// ---------------------------------------------------------------- studio
const studio = read(path.join(R, 'studio-bench.json'));
if (studio) {
  out('## Engineering Studio solvers (merged branch only)', '',
    `FailureSimulation with the backends \`src/studio/main.ts\` uses, 1,920 steps (16 s) at 120 Hz, ${studio.method.rounds} fresh processes per case. "Budget share" is two solver steps against a 16.7 ms display frame.`, '');
  out(table(['Study', 'Load', 'River', 'Nodes', 'Mean ms/step', 'p95 ms/step', 'Max ms/step', 'Real-time factor', 'Budget share at 60 Hz', 'Broken links', 'River share'],
    studio.cases.map((c) => [c.study, c.load, c.study === 'bridge' ? c.river : '–', c.outcome.nodes, f(c.meanStepMsAcrossRounds.median, 4), f(median(c.samples.map((s) => s.perStepMs.p95)), 4), f(median(c.samples.map((s) => s.perStepMs.max)), 3), `${f(c.realTimeFactor.median, 2)}×`, `${f(c.displayFrameBudgetShareAt60Hz.median * 100, 1)}%`, c.outcome.brokenCount, c.riverShareOfStepTime ? `${f(c.riverShareOfStepTime.median * 100, 1)}%` : '–'])), '');
}

// ---------------------------------------------------------------- material labs
const labs = read(path.join(R, 'labs-bench.json'));
if (labs) {
  out('## Material labs (merged branch only)', '', `Every experiment program stepped at 120 Hz to its authored length, or until ${labs.method.budgetSeconds} s of wall time.`, '');
  const ids = [...new Set(labs.cases.map((c) => c.lab))];
  out(table(['Lab', 'Programs', 'Completed', 'Median ms/step', 'p95 ms/step (median program)', 'Worst max ms/step', 'Real-time factor (median)', 'Slowest program'],
    ids.map((id) => {
      const list = labs.cases.filter((c) => c.lab === id);
      const slow = [...list].sort((a, b) => a.realTimeFactor - b.realTimeFactor)[0];
      return [id, list.length, list.filter((c) => c.completed).length, f(median(list.map((c) => c.perStepMs.median)), 4), f(median(list.map((c) => c.perStepMs.p95)), 3), f(Math.max(...list.map((c) => c.perStepMs.max)), 1), `${f(median(list.map((c) => c.realTimeFactor)), 2)}×`, `${slow.experiment} (${f(slow.realTimeFactor, 3)}×, ${f(slow.simulatedSeconds, 2)}/${f(slow.plannedSeconds, 1)} s)`];
    })), '');
  const glass = labs.cases.filter((c) => c.lab === 'glass');
  if (glass.length) out(table(['Glass program', 'Completed', 'Simulated s', 'Median ms/step', 'p95 ms/step', 'Max ms/step', 'Real-time factor', 'Phase'],
    glass.map((c) => [c.experiment, c.completed ? 'yes' : 'no (budget)', `${f(c.simulatedSeconds, 2)}/${f(c.plannedSeconds, 1)}`, f(c.perStepMs.median, 3), f(c.perStepMs.p95, 2), f(c.perStepMs.max, 1), `${f(c.realTimeFactor, 3)}×`, c.phase])), '');
}

// ---------------------------------------------------------------- math runtime (CPU)
const mathCpu = read(path.join(R, 'math-runtime-node-cpu.json'));
const solverRows = (report) => report.cases.map((c) => {
  const t = (n) => c.timings?.[n]?.completion?.p50 ?? c.timings?.[n]?.wallCompletion?.p50;
  const g = c.timings?.['webgpu-resident']?.gpuTimestamp?.p50;
  return [c.id, c.status, f(t('javascript-reference'), 5), f(t('wasm-scalar'), 5), f(t('wasm-simd'), 5), f(t('webgpu-resident'), 5), f(g, 5)];
});
if (mathCpu) {
  out('## Water solver kernels, Node CPU (math-runtime harness)', '', `Status ${mathCpu.status}; coverage ${JSON.stringify(mathCpu.comparisonCoverage)}. Per-step p50 in ms.`, '');
  out(table(['Grid', 'Validation', 'JavaScript', 'Scalar WASM', 'SIMD WASM', 'WebGPU wall', 'WebGPU timestamp'], solverRows(mathCpu)), '');
  const graph = mathCpu.executionGraph;
  if (graph?.scenarios) out(`Execution graph experiment: ${graph.status}; ${graph.scenarios.map((s) => `${s.id} ${f(s.graph?.p50 ?? s.graphTiming?.p50, 5)} ms vs eager ${f(s.eager?.p50 ?? s.eagerTiming?.p50, 5)} ms`).join('; ')}.`, '');
}

// ---------------------------------------------------------------- threaded engine
const threaded = read(path.join(R, 'threaded.json'));
if (threaded) {
  out('## Threaded engine (box3d-mt, merged branch only)', '', `${threaded.method}. ${threaded.reps} repetitions; quiet machine: ${threaded.quietMachine}; failures: ${threaded.failures.length}; exit hangs: ${threaded.exitHangs.length}.`, '');
  out(table(['Bodies', 'Config', 'Runs', 'p50 ms/step', 'Min ms/step', 'Speed-up vs single-threaded', 'Frames on requested workers', 'State equals single-threaded'],
    threaded.summary.map((s) => [s.bodies, s.config, s.runs, f(s.stepP50Median, 2), f(s.stepMin, 2), `${f(s.speedupVsSingle, 2)}×`, s.framesOnRequestedWorkers ?? '–', s.stateEqualsSingle ? 'yes' : 'NO'])), '');
}

// ---------------------------------------------------------------- build
const build = read(path.join(R, 'build-size.json'));
if (build) {
  const b = build.sizes.baseline.totals;
  const c = build.sizes.candidate.totals;
  const kb = (v) => (v / 1024).toFixed(1);
  out('## Production build', '', `vite ${build.trees.baseline.vite} (main) vs ${build.trees.candidate.vite} (merged); ${build.method.rounds} alternating builds each; compression gzip -9 and brotli q11.`, '');
  out(table(['Measure', 'Main', 'Merged', 'Change'], [
    ['Build wall time (s, median)', f(build.buildSeconds.baseline.median, 2), f(build.buildSeconds.candidate.median, 2), pct(build.buildSeconds.candidate.median / build.buildSeconds.baseline.median)],
    ['Files emitted', build.sizes.baseline.fileCount, build.sizes.candidate.fileCount, ''],
    ['All output (MiB)', (b.all.raw / 2 ** 20).toFixed(1), (c.all.raw / 2 ** 20).toFixed(1), pct(c.all.raw / b.all.raw)],
    ['JavaScript raw / brotli (KiB)', `${kb(b.javascript.raw)} / ${kb(b.javascript.brotli)}`, `${kb(c.javascript.raw)} / ${kb(c.javascript.brotli)}`, pct(c.javascript.brotli / b.javascript.brotli)],
    ['CSS raw / brotli (KiB)', `${kb(b.css.raw)} / ${kb(b.css.brotli)}`, `${kb(c.css.raw)} / ${kb(c.css.brotli)}`, pct(c.css.brotli / Math.max(1, b.css.brotli))],
    ['WebAssembly raw / brotli (KiB)', `${kb(b.wasm.raw)} / ${kb(b.wasm.brotli)}`, `${kb(c.wasm.raw)} / ${kb(c.wasm.brotli)}`, pct(c.wasm.brotli / b.wasm.brotli)],
    ['Images (MiB)', (b.images.raw / 2 ** 20).toFixed(1), (c.images.raw / 2 ** 20).toFixed(1), ''],
    ['Models (MiB)', (b.models.raw / 2 ** 20).toFixed(1), (c.models.raw / 2 ** 20).toFixed(1), ''],
    ['Video (MiB)', (b.video.raw / 2 ** 20).toFixed(1), (c.video.raw / 2 ** 20).toFixed(1), ''],
  ]), '');
  out('First-visit JavaScript and CSS per route, from the Vite manifest (an entry\'s static imports plus the dynamic import a route takes):', '');
  out(table(['Build', 'Route', 'Files', 'Raw KiB', 'gzip KiB', 'brotli KiB'],
    ['baseline', 'candidate'].flatMap((which) => Object.entries(build.sizes[which].routes ?? {}).map(([name, r]) => [which === 'baseline' ? 'main' : 'merged', name, r.files, kb(r.raw), kb(r.gzip), kb(r.brotli)]))), '');
}

// ---------------------------------------------------------------- GPU
const adapter = fs.existsSync(path.join(G, 'host/nvidia-smi.txt')) ? fs.readFileSync(path.join(G, 'host/nvidia-smi.txt'), 'utf8') : '';
if (adapter) {
  const gpu = /\|\s+\d+\s+(NVIDIA[^|]*?)\s{2,}/.exec(adapter)?.[1]?.trim();
  const driver = /Driver Version:\s*([\d.]+)/.exec(adapter)?.[1];
  out('## GPU host', '', `${gpu ?? 'NVIDIA GPU'} (RunPod Secure Cloud), driver ${driver}, Vulkan 1.4. Browser runs: Chromium ${read(path.join(G, 'browser/rendering/control/hardware-vulkan.json'))?.provenance?.browserVersion ?? ''} headless with Dawn's Vulkan backend (\`${fs.readFileSync(path.join(G, 'browser/chosen-browser-args.txt'), 'utf8').trim()}\`). Node runs: the \`webgpu\` package (Dawn) with \`backend=vulkan\`.`, '');
}
// Paired bootstrap over the harness's raw baseline/candidate frame pairs (GPU timestamp frame span).
function gpuSpanRatio(t) {
  const pairs = (t.pairs ?? []).filter((p) => Number.isFinite(p.baseline?.gpu?.frameSpanMs) && Number.isFinite(p.candidate?.gpu?.frameSpanMs));
  if (pairs.length < 4) return f(t.gpuSpanSpeedRatio, 3);
  let state = 0x9e37;
  const next = () => { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state / 0x100000000; };
  const a = pairs.map((p) => p.baseline.gpu.frameSpanMs), b = pairs.map((p) => p.candidate.gpu.frameSpanMs), boots = [];
  for (let i = 0; i < 10000; i++) { const ia = [], ib = []; for (let k = 0; k < pairs.length; k++) { const j = Math.floor(next() * pairs.length); ia.push(a[j]); ib.push(b[j]); } boots.push(median(ia) / median(ib)); }
  boots.sort((x, y) => x - y);
  return `${f(median(a) / median(b), 3)} [${f(boots[250], 3)}, ${f(boots[9750], 3)}]`;
}
for (const [kind, title] of [['control', 'colour-pipeline control baseline'], ['pinned', 'pinned baseline 031724b, unmodified']]) {
  const r = read(path.join(G, `browser/rendering/${kind}/hardware-vulkan.json`));
  if (!r) continue;
  const parity = r.parity.filter((p) => p.status === 'PASSED').length;
  out(`## Production renderer A/B on the GPU: ${title}`, '',
    `Status **${r.status}**. Image parity ${parity}/${r.parity.length} byte-exact; visibility checks ${r.visibility.filter((v) => v.status !== 'FAILED').length}/${r.visibility.length}; quality corrections ${r.qualityCorrections.filter((q) => q.status === 'PASSED').length}/${r.qualityCorrections.length}; shadow-cache checks ${r.cacheInvalidation.filter((c) => c.status === 'PASSED').length}/${r.cacheInvalidation.length}; GPU validation errors ${r.gpuValidationErrors.length}. Adapter warm-up: ${JSON.stringify(r.provenance.adapterWarmup)}.`, '');
  if (kind === 'pinned') {
    const fails = r.parity.filter((p) => p.status !== 'PASSED');
    const control = read(path.join(G, 'browser/rendering/control/hardware-vulkan.json'));
    const controlClean = control?.status === 'PASSED' && control.parity.every((p) => p.status === 'PASSED');
    if (fails.length) out(`${fails.length} images differ from the unmodified baseline: max channel difference ${Math.max(...fails.map((p) => p.pixels.maxAbsolute))} levels, median RMS ${f(median(fails.map((p) => p.pixels.rmsChannelError)), 2)} levels. ${controlClean ? 'The control run above, which applies only the exact sRGB conversion and dither to this baseline, matches every image byte for byte, so these differences are entirely that intended colour change.' : 'The control run did not pass, so these differences are not yet attributed.'}`, '');
  }
  out(table(['Scenario', 'Variant', 'GPU frame span p50 (ms) base → merged', 'GPU speed ratio [95%]', 'Wall p50 (ms) base → merged', 'Wall ratio [95%]', 'CPU encode+submit p50 (ms)'],
    r.timings.map((t) => [t.id, t.variant, `${f(t.baseline.gpuFrameSpan?.p50, 4)} → ${f(t.candidate.gpuFrameSpan?.p50, 4)}`, gpuSpanRatio(t), `${f(t.baseline.wallCompletion.p50, 3)} → ${f(t.candidate.wallCompletion.p50, 3)}`, `${f(t.uncertainty?.pairedRatioMedian, 3)} [${f(t.uncertainty?.bootstrap95PercentInterval?.[0], 3)}, ${f(t.uncertainty?.bootstrap95PercentInterval?.[1], 3)}]`, `${f(t.baseline.cpuEncodeAndSubmit?.p50, 4)} → ${f(t.candidate.cpuEncodeAndSubmit?.p50, 4)}`])), '');
}
const mathGpu = read(path.join(G, 'browser/math-runtime/browser-hardware-vulkan.json'));
if (mathGpu) {
  out('## Water solver kernels in the browser on the GPU host', '', `Status ${mathGpu.status}; coverage ${JSON.stringify(mathGpu.comparisonCoverage)}. Per-step p50 in ms; WebGPU wall includes synchronised completion, the timestamp column is GPU execution only.`, '');
  out(table(['Grid', 'Validation', 'JavaScript', 'Scalar WASM', 'SIMD WASM', 'WebGPU wall', 'WebGPU timestamp'], solverRows(mathGpu)), '');
}
const parityGpu = read(path.join(G, 'browser/math-runtime/render-parity-hardware-vulkan.json'));
if (parityGpu) {
  out(`Resident-water render parity on the GPU: ${parityGpu.status}; ${parityGpu.cases.map((c) => `${c.steps ?? c.id} steps ${c.pixels?.differingPixels ?? '–'} differing pixels (${c.waterCoveragePixels} water pixels)`).join(', ')}. uploadSurface method p50: ${parityGpu.uploadOverhead.cases.map((c) => `${c.id} ${f(c.baseline.p50 * 1000, 2)} µs (main) vs ${f(c.current.p50 * 1000, 2)} µs (merged)`).join('; ')}.`, '');
}
const startup = read(path.join(G, 'dawn/renderer-startup-vulkan.json'));
if (startup) {
  const ratio = (() => {
    let state = 11;
    const next = () => { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state / 0x100000000; };
    const a = startup.baseline.samplesMs, b = startup.optimized.samplesMs, boots = [];
    for (let i = 0; i < 20000; i++) { const ia = a.map(() => a[Math.floor(next() * a.length)]), ib = b.map(() => b[Math.floor(next() * b.length)]); boots.push(median(ia) / median(ib)); }
    boots.sort((x, y) => x - y);
    return { point: median(a) / median(b), low: boots[500], high: boots[19500] };
  })();
  out('## Renderer start-up (Dawn, Vulkan)', '', `${startup.environment.samples} fresh processes each, alternating; \`WebGPURenderer.create\` to first queue idle at 1280×720, 4,096 instances. Main ${f(startup.baseline.medianMs, 1)} ms (MAD ${f(startup.baseline.madMs, 1)}) vs merged ${f(startup.optimized.medianMs, 1)} ms (MAD ${f(startup.optimized.madMs, 1)}); speed ratio ${speed(ratio)}.`, '');
}
const on = read(path.join(G, 'dawn/partition-on-vulkan.json'));
const off = read(path.join(G, 'dawn/partition-off-vulkan.json'));
if (on && off) {
  const same = on.cases.every((c, i) => c.pixelsSha256 === off.cases[i]?.pixelsSha256);
  out('## GPU instance partition (opt-in), Dawn Vulkan', '', `Pixels identical with and without partitioning in ${same ? 'all' : 'NOT all'} ${on.cases.length} cases (counts 0–4096, 1× and 4× MSAA). Timing: total GPU pass time per frame from the renderer's own timestamp queries, 48 frames each.`, '');
  out(table(['Instances', 'Changed every frame', 'Direct p50 (ms)', 'Partitioned p50 (ms)', 'Speed ratio'],
    on.timings.map((t, i) => { const d = off.timings[i]; const a = median(d.samples), b = median(t.samples); return [t.count, t.changed ? 'yes' : 'no', f(a, 4), f(b, 4), f(a / b, 3)]; })), '');
}

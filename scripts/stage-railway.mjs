import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const dist=path.resolve('dist'),target=path.resolve('build/railway-release');
const required=['index.html','lab.html','validation/index.html','validation/validation.css','validation/validation.js','validation/validation.json','assets','studio','licenses','box3d','textures','soft-kernels-simd.wasm','soft-kernels-scalar.wasm','box3d/box3d.js','box3d/box3d.wasm','box3d/box3d-mt.js','box3d/box3d-mt.wasm'];
for(const name of required)assert.ok(fs.existsSync(path.join(dist,name)),`Required production artifact missing: ${name}`);
fs.mkdirSync(path.dirname(target),{recursive:true});
if(fs.existsSync(target)){
  assert.ok(fs.existsSync(path.join(target,'.box3d-generated-stage')),'Refusing to replace a directory not owned by this stager');
  fs.rmSync(target,{recursive:true});
}
fs.cpSync(dist,target,{recursive:true});
fs.writeFileSync(path.join(target,'.box3d-generated-stage'),'Generated by scripts/stage-railway.mjs\n');
for(const file of ['Dockerfile','Caddyfile','serve-railway.sh'])fs.copyFileSync(path.join('deploy/railway',file),path.join(target,file));
if(!fs.existsSync(path.join(target,'release-info.json'))){
  const commit=execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
  fs.writeFileSync(path.join(target,'release-info.json'),JSON.stringify({commit,version:JSON.parse(fs.readFileSync('package.json','utf8')).version,applications:['studio','physics-lab']},null,2)+'\n');
}
for(const file of ['robots.txt','sitemap.xml'])assert.ok(fs.existsSync(path.join(target,file)),`Missing ${file}; retain the existing public metadata`);
console.log(`Both application entries and native/soft runtimes staged at ${target}. Nothing deployed.`);
